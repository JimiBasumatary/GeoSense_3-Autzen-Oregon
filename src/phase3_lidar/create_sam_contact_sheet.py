
from pathlib import Path

import pandas as pd
from PIL import Image, ImageDraw

ROOT = Path(r"D:\GeoSense_Phase3")
OUT_DIR = ROOT / "outputs" / "sam_rooftop"

IMAGE_PATH = ROOT / "data" / "aerial" / "autzen_naip_preview.jpg"
CSV_PATH = OUT_DIR / "autzen_sam_masks.csv"
MASK_DIR = OUT_DIR / "individual_masks"
OUTPUT_PATH = OUT_DIR / "largest_masks_contact_sheet.jpg"

# Select the 15 largest SAM masks.
df = pd.read_csv(CSV_PATH)
df = df.sort_values("area_pixels", ascending=False).head(15)

original = Image.open(IMAGE_PATH).convert("RGB")

cell_width = 190
cell_height = 210
columns = 3
rows = 5

sheet = Image.new(
    "RGB",
    (columns * cell_width, rows * cell_height),
    "white",
)
draw = ImageDraw.Draw(sheet)

for index, row in enumerate(df.itertuples(index=False)):
    mask_id = int(row.mask_id)

    # Load the actual binary mask generated by SAM.
    mask_path = MASK_DIR / f"mask_{mask_id:04d}.png"
    mask = Image.open(mask_path).convert("L")

    # Crop the aerial image to the mask bounding box.
    x = int(row.bbox_x)
    y = int(row.bbox_y)
    width = int(row.bbox_width)
    height = int(row.bbox_height)

    crop = original.crop((x, y, x + width, y + height))
    crop_mask = mask.crop((x, y, x + width, y + height))

    # Show the mask boundary in red on its image crop.
    boundary = crop_mask.filter(Image.Filter.FIND_EDGES) if False else None

    import numpy as np

    mask_array = np.array(crop_mask)
    image_array = np.array(crop)

    padded = np.pad(mask_array > 0, 1)
    edges = (
        padded[1:-1, :-2]
        | padded[1:-1, 2:]
        | padded[:-2, 1:-1]
        | padded[2:, 1:-1]
    ) & ~(mask_array > 0)

    image_array[edges] = [255, 0, 0]
    crop = Image.fromarray(image_array)
    crop.thumbnail((170, 155))

    col = index % columns
    row_num = index // columns
    left = col * cell_width
    top = row_num * cell_height

    sheet.paste(
        crop,
        (
            left + (cell_width - crop.width) // 2,
            top + 3,
        ),
    )

    draw.text(
        (left + 5, top + 165),
        f"Mask {mask_id} | {int(row.area_pixels)} pixels",
        fill="black",
    )
    draw.text(
        (left + 5, top + 183),
        f"IoU {row.predicted_iou:.2f}",
        fill="black",
    )
    draw.text(
        (left + 5, top + 197),
        f"Stability {row.stability_score:.2f}",
        fill="black",
    )

sheet.save(OUTPUT_PATH, quality=95)

print("Contact sheet created successfully.")
print("Masks displayed:", len(df))
print("Output:", OUTPUT_PATH)
